    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is unavailable; production Qwen GRPO requires a CUDA worker")
    devices = _resolve_devices(args, torch)
    scenarios_per_update = (
        len(devices) if args.scenarios_per_update is None else int(args.scenarios_per_update)
    )
    if scenarios_per_update > len(devices):
        raise ValueError(
            "--scenarios_per_update cannot exceed the number of rollout devices; "
            "each model replica may execute only one scenario at a time"
        )

