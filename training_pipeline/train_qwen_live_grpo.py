def _git_value(*args: str) -> str | None:
    proc = subprocess.run(["git", *args], text=True, stdout=subprocess.PIPE,
                          stderr=subprocess.DEVNULL, check=False)
    return proc.stdout.strip() or None


def _write_manifest(path: Path, *, args: argparse.Namespace, records: list[Any],
                    devices: list[str], torch: Any) -> None:
    # The CLI has no credentials; token counts are scientific hyperparameters
    # and must remain in the manifest. Credentials are represented only by a
    # boolean environment-presence flag below.
    safe_args = dict(vars(args))
    manifest = {
        "format": "qwen_live_grpo_run_manifest_v1", "created_unix": time.time(),
        "argv": sys.argv, "arguments": safe_args, "python": sys.version,
        "platform": platform.platform(), "hostname": platform.node(),
        "git_commit": _git_value("rev-parse", "HEAD"),
        "git_status": _git_value("status", "--short"),
        "torch_version": torch.__version__, "cuda_version": torch.version.cuda,
        "devices": [{"name": torch.cuda.get_device_name(d), "capability": torch.cuda.get_device_capability(d)} for d in devices],
        "scenario_ids": [r.scenario_id for r in records],
        "scenario_selection_sha256": hashlib.sha256("\n".join(r.scenario_id for r in records).encode()).hexdigest(),
        "environment_presence": {"OPENAI_API_KEY": bool(os.environ.get("OPENAI_API_KEY"))},
    }
    rendered = json.dumps(manifest, indent=2, sort_keys=True, default=str)
    path.write_text(rendered, encoding="utf-8")
    history = path.parent / "run_manifests"
    history.mkdir(exist_ok=True)
    run_id = f"run-{int(manifest['created_unix'] * 1000)}-{os.getpid()}"
    (history / f"{run_id}.json").write_text(rendered, encoding="utf-8")


def _prune_checkpoints(directory: Path, keep_last: int) -> None:
    if keep_last <= 0:
        return
    paths = sorted(directory.glob("update-*.pt"))
    for path in paths[:-keep_last]:
        path.unlink()


def _resolve_devices(args: argparse.Namespace, torch: Any) -> list[str]:
    if args.device:
        raw = [str(args.device)]
    elif str(args.devices).strip().lower() == "auto":
        raw = [f"cuda:{index}" for index in range(int(torch.cuda.device_count()))]
    else:
        raw = [part.strip() for part in str(args.devices).split(",") if part.strip()]
    if not raw:
        raise ValueError("no CUDA rollout devices were selected")
    normalized: list[str] = []
    for value in raw:
        device = torch.device(value)
        if device.type != "cuda":
            raise ValueError(f"parallel Qwen rollout requires CUDA devices; got {value!r}")
        index = torch.cuda.current_device() if device.index is None else int(device.index)
        if index < 0 or index >= int(torch.cuda.device_count()):
            raise ValueError(f"CUDA device index is unavailable: {value!r}")
        canonical = f"cuda:{index}"
        if canonical in normalized:
            raise ValueError(f"duplicate rollout device: {canonical}")
        normalized.append(canonical)
    return normalized


@dataclass
class _RolloutWorker:
    index: int
    device: str
    model: Any
    rca_policy: Any
    rca_solver: Any
    action_policy: Any
    action_agent: Any
    twin: Any
    checkpointing: str


def _run_worker_rollout(
    worker: _RolloutWorker,
    rec: Any,
    *,
    batch_offset: int,
    args: argparse.Namespace,
    policy_version: str,
    bounded: Any,
    run_end_to_end_trajectory_group: Any,
    rca_recent_performance: dict[str, Any] | None = None,
    action_recent_performance: dict[str, Any] | None = None,
) -> dict[str, Any]:
    import torch

    # Some CUDA libraries consult the thread-local current device even when all
    # tensors carry an explicit placement. Keep each rollout thread pinned.
    with torch.cuda.device(worker.device):
        result = run_end_to_end_trajectory_group(
            rec.full_state, rec.compressed_state,
            rca_instruction_policy=worker.rca_policy, rca_solver=worker.rca_solver,
            action_prompt_policy=worker.action_policy, action_agent=worker.action_agent,
            twin_verifier=worker.twin, trajectory_group_size=args.trajectory_group_size,
            rca_max_iterations=args.rca_max_iterations,
            action_max_iterations=args.action_max_iterations,
            rca_policy_model_name=f"{args.model}+lora_rca",
            action_policy_model_name=f"{args.model}+lora_action",
            policy_version=policy_version,
            min_twin_reproduction_score=args.min_twin_reproduction_score,
            bounded_agent_state_config=bounded,
            rca_recent_performance=rca_recent_performance,
            action_recent_performance=action_recent_performance,
        )
    return {
        "worker_index": worker.index,
        "worker_device": worker.device,
        "batch_offset": batch_offset,
        "scenario_id": rec.scenario_id,
        "result": result,
    }


def main() -> None:
    args = _parser().parse_args()
